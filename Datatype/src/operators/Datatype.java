package operators;

public class Datatype {
public static void main(String[] args) {
	
	//Numeric DT 
	
	byte num1 = 127; // it will store the data -127 to 127
	System.out.println(num1);
	
	
	long numm = num1;
	System.out.println(numm);
	
	short num2 = 500;
	System.out.println(num2);
	
	
	int num3 = 50000;
	System.out.println(num3);
	
	long num4= 700000000;
	int store = (int)num4;
	System.out.println(store);
	
	float num5 = 89.142434f;
	System.out.println(num5);
	
	double num6 = 78.9090890811111111111111;
	System.out.println(num6);
	
	//boolean 
	boolean eligibletoVote = true;
	System.out.println(eligibletoVote);
	
	char firstCharacter = 'a';
	System.out.println((char)(firstCharacter+1));// print in char with explicitly
	
	
	
	
	
	
}
}
